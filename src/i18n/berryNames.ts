export function getLocalizedBerryName(
  berryId: string,
  language: SupportedLanguage,
  defaultName?: string
): string {
  const normalizedId = berryId.toLowerCase().replace(/[\s_-]berry$/i, "").trim();
  const entry = BERRY_NAMES[normalizedId];
  if (!entry) return defaultName || berryId;

  if (language === "zh-CN") return entry["zh-CN"];
  if (language === "zh-TW") return entry["zh-TW"];
  if (language === "ja" && entry.ja) return entry.ja;
  if (language === "es" && entry.es) return entry.es;
  if (language === "fr" && entry.fr) return entry.fr;
  if (language === "de" && entry.de) return entry.de;
  if (language === "pt-BR" && entry.es) return entry.es; // PT PokeMMO uses standard or Spanish names
  return entry.en || defaultName || berryId;
}
